def by_id() -> dict[str, dict]:
    return {c["id"]: c for c in COMPONENTS}


def markdown() -> str:
    lines = ["# Componentes de Tableau: definición, uso, recomendación y cómo los construye tableu", "",
             "Cada componente nombra el XML que Tableau escribe para él (comprobado contra `xml-catalog.json`) y "
             "la operación de tableu que lo construye. `tests/test_components.py` construye cada uno y verifica "
             "su estructura. «Falta» = en `tableu://coverage-gaps`.", ""]
    area = None
    for c in COMPONENTS:
        if c["area"] != area:
            area = c["area"]
            lines += [f"## {area}", ""]
        lines += [f"### {c['name']}", "",
                  f"- **Qué es:** {c['definition']}",
                  f"- **Cuándo usarlo:** {c['use']}",
                  f"- **Recomendación:** {c['recommendation']} ([fuente]({c['source']}))",
                  f"- **XML de Tableau:** {', '.join('`' + x + '`' for x in c['xml'])}",
                  f"- **tableu:** {('`' + c['op'] + '`') if c['op'] else 'falta'}", ""]
    return "\n".join(lines)
